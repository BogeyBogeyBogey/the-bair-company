def partner_centres(snapshot: dict) -> dict:
    centres = {}
    network = snapshot.get("network", {})
    for partner in network.get("partners", []):
        centres[partner["id"]] = {
            "lat": float(partner.get("lat") or 50.9),
            "lon": float(partner.get("lon") or 4.4),
            "name": partner.get("name") or partner["id"],
            "region": partner.get("region") or "",
            "cities": partner.get("cities") or [],
            "capacity": int(partner.get("capacity") or 180),
            "tier": partner.get("tier") or "gold",
        }
    return centres


def best_assessment(property_row: dict) -> dict:
    assessments = property_row.get("assessments") or {}
    if not assessments:
        return {}
    return max(assessments.values(), key=lambda item: float(item.get("score") or 0))


def fake_address(index: int, partner: dict, rnd: random.Random) -> tuple[str, str]:
    root = STREET_ROOTS[(index + rnd.randint(0, 7)) % len(STREET_ROOTS)]
    suffix = STREET_SUFFIXES[(index // 3 + rnd.randint(0, 3)) % len(STREET_SUFFIXES)]
    number = 2 + ((index * 7 + rnd.randint(0, 19)) % 186)
    if number % 2:
        number += 1
    city = (partner.get("cities") or [partner.get("region") or "Demo"])[index % max(1, len(partner.get("cities") or []))]
    return f"{root}{suffix} {number}", city


def grade_for(score: int, visual_status: str) -> str:
    if score >= 78:
        return "A+"
    if score >= 72:
        return "A"
    if score >= 64:
        return "B"
    return "C"


