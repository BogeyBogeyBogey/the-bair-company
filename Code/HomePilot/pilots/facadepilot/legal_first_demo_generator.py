def final_score(components: dict) -> int:
    # Visual verification is neutral when not yet field-verified; it must not
    # punish broad legal/open-data scoring before a site audit.
    visual_neutral = 72 if components["visual_verification"] == 0 else components["visual_verification"]
    score = (
        components["property_fit"] * 0.30
        + visual_neutral * 0.25
        + components["territory_fit"] * 0.15
        + components["renovation_context"] * 0.15
        + components["campaign_readiness"] * 0.10
        + components["value_fit"] * 0.05
    )
    return int(round(score))


