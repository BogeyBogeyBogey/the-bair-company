def draw_facade(path: Path, property_row: dict, facade_style: str, house_type: str, rnd: random.Random) -> None:
    width, height = PHOTO_SIZE
    sky_top = (118 + rnd.randint(-8, 16), 157 + rnd.randint(-8, 12), 185 + rnd.randint(-8, 12))
    sky_bottom = (205 + rnd.randint(-8, 12), 218 + rnd.randint(-8, 10), 226 + rnd.randint(-8, 10))
    img = Image.new("RGB", (width, height), sky_top)
    draw = ImageDraw.Draw(img)

    for y in range(height):
        t = y / max(1, height - 1)
        color = tuple(int(sky_top[i] * (1 - t) + sky_bottom[i] * t) for i in range(3))
        draw.line([(0, y), (width, y)], fill=color)

    horizon = 292 + rnd.randint(-18, 18)
    draw.rectangle([0, horizon, width, height], fill=(125, 144, 111))
    draw.polygon([(0, height), (width, height), (width, horizon + 42), (0, horizon + 82)], fill=(116, 112, 101))
    draw.polygon([(0, height), (width, height), (width, horizon + 90), (0, horizon + 132)], fill=(74, 77, 72))
    draw.polygon([(0, horizon + 86), (width, horizon + 44), (width, horizon + 70), (0, horizon + 112)], fill=(187, 181, 161))

    for _ in range(5):
        tx = rnd.randint(-40, width - 20)
        trunk = (88 + rnd.randint(-10, 10), 67 + rnd.randint(-8, 8), 45)
        leaf = (57 + rnd.randint(-8, 15), 102 + rnd.randint(-16, 14), 66 + rnd.randint(-10, 16))
        draw.rectangle([tx + 18, horizon - 80, tx + 27, horizon + 15], fill=trunk)
        for blob in range(4):
            bx = tx - 14 + rnd.randint(-10, 18)
            by = horizon - 148 + rnd.randint(-12, 18)
            draw.ellipse([bx, by, bx + 72, by + 78], fill=leaf)

    house_w = {
        "rijwoning": rnd.randint(250, 300),
        "halfopen": rnd.randint(300, 360),
        "vrijstaand": rnd.randint(360, 430),
        "bungalow": rnd.randint(410, 470),
        "hoekwoning": rnd.randint(330, 390),
    }[house_type]
    house_h = rnd.randint(150, 205) if house_type != "bungalow" else rnd.randint(120, 155)
    x0 = (width - house_w) // 2 + rnd.randint(-30, 30)
    y1 = horizon + rnd.randint(32, 56)
    y0 = y1 - house_h
    x1 = x0 + house_w

    palettes = {
        "brick": [(151, 86, 61), (166, 101, 72), (123, 69, 55)],
        "painted_brick": [(205, 207, 196), (190, 193, 182), (217, 216, 204)],
        "old_crepi": [(219, 212, 188), (199, 190, 166), (232, 225, 202)],
        "mixed_facade": [(176, 157, 132), (209, 207, 195), (122, 92, 75)],
        "sixties_brick": [(177, 120, 78), (198, 139, 91), (145, 96, 70)],
    }
    facade_color = rnd.choice(palettes[facade_style])
    shadow = tuple(max(0, c - 34) for c in facade_color)
    draw.rectangle([x0 + 14, y0 + 18, x1 + 18, y1 + 12], fill=(45, 50, 53))
    draw.rectangle([x0, y0, x1, y1], fill=facade_color)
    # Soft sunlight and grime gradients make the generated asset read less flat.
    for yy in range(y0, y1):
        t = (yy - y0) / max(1, y1 - y0)
        shade = int(18 * t)
        draw.line([(x0, yy), (x1, yy)], fill=tuple(max(0, c - shade) for c in facade_color))
    sun_patch = Image.new("RGBA", (width, height), (0, 0, 0, 0))
    sun_draw = ImageDraw.Draw(sun_patch)
    sun_draw.ellipse([x0 - 120, y0 - 90, x0 + 240, y0 + 190], fill=(255, 240, 190, 28))
    img = Image.alpha_composite(img.convert("RGBA"), sun_patch).convert("RGB")
    draw = ImageDraw.Draw(img)

    if facade_style in {"brick", "sixties_brick"}:
        mortar = tuple(min(255, c + 34) for c in facade_color)
        for yy in range(y0 + 9, y1, 18):
            draw.line([(x0, yy), (x1, yy)], fill=mortar, width=1)
        for row, yy in enumerate(range(y0 + 9, y1, 18)):
            offset = 0 if row % 2 else 24
            for xx in range(x0 + offset, x1, 48):
                draw.line([(xx, yy), (xx, min(y1, yy + 18))], fill=mortar, width=1)
    else:
        for _ in range(900):
            xx = rnd.randint(max(0, x0), min(width - 1, x1))
            yy = rnd.randint(max(0, y0), min(height - 1, y1))
            delta = rnd.randint(-10, 10)
            base = tuple(max(0, min(255, c + delta)) for c in facade_color)
            draw.point((xx, yy), fill=base)

    roof_color = rnd.choice([(89, 67, 63), (111, 69, 51), (64, 72, 78), (119, 80, 57)])
    roof_h = rnd.randint(52, 82)
    if house_type == "bungalow":
        draw.polygon([(x0 - 35, y0 + 18), ((x0 + x1) // 2, y0 - roof_h), (x1 + 35, y0 + 18)], fill=roof_color)
    else:
        draw.polygon([(x0 - 25, y0 + 16), (x0 + house_w // 2, y0 - roof_h), (x1 + 25, y0 + 16)], fill=roof_color)
    for yy in range(y0 - roof_h + 10, y0 + 14, 12):
        draw.line([(x0 - 20, yy), (x1 + 20, yy + rnd.randint(-3, 3))], fill=tuple(max(0, c - 16) for c in roof_color), width=1)

    window_cols = 2 if house_w < 330 else 3
    floors = 1 if house_type == "bungalow" else 2
    win_w = int(house_w / (window_cols + 1) * 0.38)
    win_h = 42 if floors == 2 else 52
    glass = (44, 70, 86)
    frame = (232, 238, 237)
    for floor in range(floors):
        wy = y0 + 34 + floor * 72
        for col in range(window_cols):
            if floor == floors - 1 and col == window_cols // 2 and rnd.random() < 0.28:
                continue
            wx = x0 + int((col + 1) * house_w / (window_cols + 1)) - win_w // 2
            draw.rectangle([wx - 4, wy - 4, wx + win_w + 4, wy + win_h + 4], fill=frame)
            draw.rectangle([wx, wy, wx + win_w, wy + win_h], fill=glass)
            draw.polygon([(wx, wy), (wx + win_w, wy), (wx + win_w // 2, wy + win_h)], fill=(69, 103, 123))
            draw.line([(wx + win_w // 2, wy), (wx + win_w // 2, wy + win_h)], fill=frame, width=2)
            draw.line([(wx, wy + win_h // 2), (wx + win_w, wy + win_h // 2)], fill=frame, width=2)
            draw.rectangle([wx + 6, wy + 5, wx + max(8, win_w // 2), wy + 10], fill=(86, 119, 133))

    door_w = 38 + rnd.randint(0, 18)
    door_h = 78 + rnd.randint(0, 16)
    door_x = x0 + house_w // 2 - door_w // 2 + rnd.randint(-50, 50)
    door_y = y1 - door_h
    door_color = rnd.choice([(54, 74, 83), (86, 73, 57), (57, 93, 79), (102, 65, 54)])
    draw.rectangle([door_x - 4, door_y - 4, door_x + door_w + 4, y1], fill=frame)
    draw.rectangle([door_x, door_y, door_x + door_w, y1], fill=door_color)
    draw.ellipse([door_x + door_w - 11, door_y + door_h // 2, door_x + door_w - 6, door_y + door_h // 2 + 5], fill=(220, 190, 100))

    if house_w > 370 and rnd.random() < 0.55:
        garage_w = 86
        gx = x1 - garage_w - 24
        gy = y1 - 70
        draw.rectangle([gx, gy, gx + garage_w, y1], fill=(211, 216, 214))
        for yy in range(gy + 10, y1, 12):
            draw.line([(gx, yy), (gx + garage_w, yy)], fill=(156, 162, 162), width=1)

    draw.rectangle([0, height - 32, width, height], fill=(8, 13, 19))
    draw.text((18, height - 23), "synthetic demo visual - no real building / no Google source", fill=(216, 225, 232))

    noise = Image.effect_noise((width, height), 7).convert("L")
    noise_rgb = Image.merge("RGB", (noise, noise, noise)).point(lambda p: int(p * 0.08))
    img = Image.blend(img, noise_rgb, 0.10)
    vignette = Image.new("L", (width, height), 0)
    vig = ImageDraw.Draw(vignette)
    vig.ellipse([-120, -80, width + 120, height + 120], fill=210)
    vignette = vignette.filter(ImageFilter.GaussianBlur(70))
    dark = Image.new("RGB", (width, height), (17, 20, 22))
    img = Image.composite(img, dark, vignette)
    img = img.filter(ImageFilter.GaussianBlur(0.25))
    img = img.filter(ImageFilter.UnsharpMask(radius=1.0, percent=105, threshold=3))
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "JPEG", quality=78, optimize=True, progressive=True)


