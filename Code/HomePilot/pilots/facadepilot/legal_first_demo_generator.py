def localize_visible_text(value):
    replacements = {
        "All 2,000 facade visuals": "All 2.000 facade visuals",
        "visible facade m2 where available": "visible facade area in m² where available",
        "237833 facade m2 and EUR 36443703 pipeline value": "237.833 m² gevel and EUR 36.443.703 pipeline value",
        "1187 high-priority records, with 237833 facade m2 and EUR 36443703 pipeline value": "1.187 high-priority records, with 237.833 m² gevel and EUR 36.443.703 pipeline value",
        "100.0%": "100,0%",
        "33.3%": "33,3%",
        "11.1%": "11,1%",
    }
    if isinstance(value, dict):
        for key, item in list(value.items()):
            value[key] = localize_visible_text(item)
        return value
    if isinstance(value, list):
        return [localize_visible_text(item) for item in value]
    if isinstance(value, str):
        for old, new in replacements.items():
            value = value.replace(old, new)
    return value


